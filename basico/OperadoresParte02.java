package flamingo.aprendendo.basico;

public class OperadoresParte02 {
    /*
    < menor que
    > menor que
    <= menor ou igual
    >= maior ou igual
    == igual a
    != diferende de
     */

    static void main() {

        int numero01 = 7;
        int numero02 = 10;


        System.out.println("Operadores Parte 2");
        System.out.println(numero01 > numero02);
        System.out.println(numero01 < numero02);
        System.out.println(numero01 <= numero02);
        System.out.println(numero01 >= numero02);
        System.out.println(numero01 == numero02);
        System.out.println(numero01 != numero02);
    }
}
