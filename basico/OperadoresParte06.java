package flamingo.aprendendo.basico;

public class OperadoresParte06 {
    static void main() {
        //Incremento e Decremento

        int contador = 0;
        contador = contador + 1;
        contador += 1;
        contador++;

        //Decremento

        contador = contador - 1;
        contador -= 1;
        contador--;

        System.out.println(++contador);
    }
}
